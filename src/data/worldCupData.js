export function createGroupMatches(group) {
  const [teamA, teamB, teamC, teamD] = group.teams
  const createMatch = (index, home, away) => {
    const id = `${group.id}-${index}`

    return { id, groupId: group.id, home, away, kickoff: groupMatchKickoffs[id] }
  }

  return [
    createMatch(1, teamA, teamB),
    createMatch(2, teamC, teamD),
    createMatch(3, teamA, teamC),
    createMatch(4, teamD, teamB),
    createMatch(5, teamD, teamA),
    createMatch(6, teamB, teamC),
  ]
}

export function calculateGroupStandings(group, results) {
  const table = buildInitialStandings(group.teams)
  const rowsByTeam = Object.fromEntries(table.map((row) => [row.team, row]))

  createGroupMatches(group).forEach((match) => {
    const result = results[match.id]
    const homeGoals = Number(result?.homeGoals)
    const awayGoals = Number(result?.awayGoals)

    if (!isFinishedResult(result, result?.kickoff || match.kickoff)) return

    const home = rowsByTeam[match.home]
    const away = rowsByTeam[match.away]

    home.played += 1
    away.played += 1
    home.goalsFor += homeGoals
    home.goalsAgainst += awayGoals
    away.goalsFor += awayGoals
    away.goalsAgainst += homeGoals

    if (homeGoals > awayGoals) {
      home.won += 1
      away.lost += 1
      home.points += 3
    } else if (homeGoals < awayGoals) {
      away.won += 1
      home.lost += 1
      away.points += 3
    } else {
      home.drawn += 1
      away.drawn += 1
      home.points += 1
      away.points += 1
    }
  })

  return table
    .map((row) => ({
      ...row,
      goalDifference: row.goalsFor - row.goalsAgainst,
    }))
    .sort((a, b) => {
      if (b.points !== a.points) return b.points - a.points
      if (b.goalDifference !== a.goalDifference) return b.goalDifference - a.goalDifference
      if (b.goalsFor !== a.goalsFor) return b.goalsFor - a.goalsFor
      return a.team.localeCompare(b.team)
    })
}

